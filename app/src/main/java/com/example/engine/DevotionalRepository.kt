class DevotionalSoundSynthesizer {
    private var isPlaying = false
    private var audioTrack: AudioTrack? = null
    private var job: Job? = null

    fun playOmChant(durationSec: Int = 4, onComplete: () -> Unit = {}) {
        onComplete()
    }

    fun playSereneTone(baseFreq: Double = 432.0, durationSec: Int = 10, onComplete: () -> Unit) {
        stop()
        isPlaying = true

        job = CoroutineScope(Dispatchers.Default).launch {
            try {
                val sampleRate = 44100
                val numSamples = sampleRate * durationSec
                val buffer = ShortArray(numSamples)

                // Generate harmonic meditative bell tone with soft envelope decay (Om vibration)
                for (i in 0 until numSamples) {
                    val t = i.toDouble() / sampleRate
                    // Envelope that repeats in 4-second meditative cycles
                    val cycleT = t % 4.0
                    val envelope = Math.exp(-cycleT * 1.5)

                    // Final fade out to prevent sudden popping at the absolute end of play
                    val fadeOut = if (t > durationSec - 1.2) ((durationSec - t) / 1.2).coerceIn(0.0, 1.0) else 1.0
                    val finalEnvelope = envelope * fadeOut

                    // Fundamental frequency + gentle 3rd and 5th harmonics
                    val fundamental = sin(2.0 * Math.PI * baseFreq * t)
                    val harmonic2 = 0.4 * sin(2.0 * Math.PI * (baseFreq * 1.5) * t)
                    val harmonic3 = 0.2 * sin(2.0 * Math.PI * (baseFreq * 2.0) * t)

                    val sampleValue = (fundamental + harmonic2 + harmonic3) * finalEnvelope * 0.7
                    buffer[i] = (sampleValue * Short.MAX_VALUE).toInt().coerceIn(Short.MIN_VALUE.toInt(), Short.MAX_VALUE.toInt()).toShort()
                }

                val minBufSize = AudioTrack.getMinBufferSize(
                    sampleRate,
                    AudioFormat.CHANNEL_OUT_MONO,
                    AudioFormat.ENCODING_PCM_16BIT
                )

                audioTrack = AudioTrack.Builder()
                    .setAudioAttributes(
                        AudioAttributes.Builder()
                            .setUsage(AudioAttributes.USAGE_MEDIA)
                            .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
                            .build()
                    )
                    .setAudioFormat(
                        AudioFormat.Builder()
                            .setEncoding(AudioFormat.ENCODING_PCM_16BIT)
                            .setSampleRate(sampleRate)
                            .setChannelMask(AudioFormat.CHANNEL_OUT_MONO)
                            .build()
                    )
                    .setBufferSizeInBytes(buffer.size * 2)
                    .setTransferMode(AudioTrack.MODE_STATIC)
                    .build()

                audioTrack?.write(buffer, 0, buffer.size)
                audioTrack?.play()

                delay(durationSec * 1000L)
            } catch (e: Exception) {
                // Ignore interruption
            } finally {
                withContext(Dispatchers.Main) {
                    stop()
                    onComplete()
                }
            }
        }
    }

    fun stop() {
        isPlaying = false
        job?.cancel()
        job = null
        try {
            audioTrack?.stop()
            audioTrack?.release()
        } catch (_: Exception) {}
        audioTrack = null
    }

    fun isCurrentlyPlaying(): Boolean = isPlaying
}
