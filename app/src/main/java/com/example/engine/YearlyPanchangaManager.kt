        val adayaList = rashis.mapIndexed { idx, name ->
            val ad = ((idx * 3 + year % 7) % 14) + 1
            val vy = ((idx * 5 + year % 5) % 14) + 1
            val rp = ((idx * 2 + year % 4) % 7) + 1
            val av = ((idx * 4 + year % 6) % 7) + 1
            val score = "${((ad * 8) / (ad + vy)).coerceIn(1, 8)}/8"
            val percent = (50 + (ad - vy) * 3).coerceIn(45, 95)
            RashiAdayaVyaya(
                rashiName = name,
                rashiEmoji = rashiEmojis[idx],
                adayam = ad,
                vyayam = vy,
                rajapoojyam = rp,
