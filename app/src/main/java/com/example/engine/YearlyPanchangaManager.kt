    private fun generateAlgorithmicSamvatsaram(year: Int): YearlyPanchangaOverview {
        val samvatsaraIndex = (year - 4) % 60
        val samvatsaraName = TELUGU_SAMVATSARAS.getOrElse(samvatsaraIndex) { "శుభకృత్" }

        val rashis = listOf("మేషం", "వృషభం", "మిథునం", "కర్కాటకం", "సింహం", "కన్య", "తుల", "వృశ్చికం", "ధనుస్సు", "మకరం", "కుంభం", "మీనం")
