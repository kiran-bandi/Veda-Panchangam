    fun getYearlyPanchanga(year: Int, language: AppLanguage = AppLanguage.TE): YearlyPanchangaOverview {
        return when (year) {
            2024 -> getKrodhiSamvatsaram()
            2025 -> getVishvavasuSamvatsaram()
            2026 -> getParabhavaSamvatsaram()
            2027 -> getPlavangaSamvatsaram()
            2028 -> getKilakaSamvatsaram()
            else -> generateAlgorithmicSamvatsaram(year)
        }
    }

